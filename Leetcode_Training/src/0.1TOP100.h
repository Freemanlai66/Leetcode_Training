    // 将生成答案和生成prefix数组的过程合并到一次遍历里，把答案数组和suffix也合并在一起
    // 可以省去两个大小为n的额外数组（如果返回值不计入，那么空间复杂度为O(1)）
 
    class Solution {
    public:
        vector<int> productExceptSelf(vector<int>& nums) {
            int n = nums.size();
            vector<int> suffix(n, 0);
            suffix[n - 1] = 1;
            for (int i = n - 2; i >= 0; --i) {
                suffix[i] = suffix[i + 1] * nums[i + 1];
            }

            int pre = 1;
            for (int i = 0; i < n; ++i) {
                suffix[i] *= pre;
                pre *= nums[i];
            }

            return suffix;
        }
    };
