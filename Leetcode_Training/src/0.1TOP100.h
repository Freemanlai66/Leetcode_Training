{   // DFS递归写法，把拷贝节点的工作全部丢给下一层的递归函数，更符合DFS的思想，但是不好改成迭代做法
    class Node {
    public:
        int val;
        vector<Node*> neighbors;
        Node() {
            val = 0;
            neighbors = vector<Node*>();
        }
        Node(int _val) {
            val = _val;
            neighbors = vector<Node*>();
        }
        Node(int _val, vector<Node*> _neighbors) {
            val = _val;
            neighbors = _neighbors;
        }
    };
    class Solution {
    private:
        unordered_map<Node*, Node*> mp;   // 旧节点 -> 克隆节点

    public:
        Node* cloneGraph(Node* node) {
            if (node == nullptr) return nullptr;

            // 1) 克隆过了？直接返回现成的克隆
            if (mp.count(node)) return mp[node];

            // 2) 先只拷贝 val，造一个"空壳"克隆
            Node* clone = new Node(node->val);
            mp[node] = clone;   // 先登记，再递归！

            // 3) 逐个克隆邻居，接到 clone 上
            for (Node* nei : node->neighbors) {
                // 关键在这里，遍历邻居进行连线时，用的是递归结果
                clone->neighbors.push_back(cloneGraph(nei));
            }
            return clone;
        }
    };
}
