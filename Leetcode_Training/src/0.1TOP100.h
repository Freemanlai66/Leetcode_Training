namespace s133m1
{   // 自己思路修改而来的DFS做法
    // 在遍历邻居时就生成拷贝节点，o1的DFS做法中，遍历邻居时只连线，而不生成拷贝节点，更简洁
    class Node {
    public:
        int val;
        vector<Node*> neighbors;
        Node() {
            val = 0;
            neighbors = vector<Node*>();
        }
        Node(int _val) {
            val = _val;
            neighbors = vector<Node*>();
        }
        Node(int _val, vector<Node*> _neighbors) {
            val = _val;
            neighbors = _neighbors;
        }
    };
    class Solution {
    public:
        Node* cloneGraph(Node* node) {
            // 节点数为0时要特判
            if (!node) return nullptr;

            unordered_map<Node*, Node*> mp; // old -> new

            auto dfs = [&](auto&& dfs, Node* from) -> void {
                // 确保进入每个dfs递归前，对应的节点都已经生成了拷贝
                for (auto to : from->neighbors) {
                    if (mp.count(to)) {
                        mp[from]->neighbors.push_back(mp[to]);
                    }
                    else {
                        mp[to] = new Node(to->val);
                        mp[from]->neighbors.push_back(mp[to]);
                        dfs(dfs, to);
                    }
                }
                };

            mp[node] = new Node(node->val);
            dfs(dfs, node);

            return mp[node];
        }
    };
}
