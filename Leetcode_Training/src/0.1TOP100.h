namespace s73o2
{   // 感觉有点为了解题而解题了，实际节省的内存空间量很少，但好在o2解法也不难理解和掌握，一切为了面试
    // 不使用额外数组，空间复杂度(1)
    // 主要思路是用原矩阵的第一行和第一列代替o1中的布尔数组 
    class Solution {
    public:
        void setZeroes(vector<vector<int>>& matrix) {
            int m = matrix.size(), n = matrix[0].size();
            // 预先通过两个布尔值记录第一行第一列中是否有0
            // 单独处理第一行第一列是为了规避以下BUG：
            // 比如第一行全为1，第一列存在0，如果用第一行和第一列来完整存储所有行/列的结果
            // 那么会因为第一列存在0，将matrix[0][0] = 0，从而误认为第一行和第一列都包含0
            bool rowHasZero = false;
            bool colHasZero = false;
            for (int i = 0; i < m; ++i) {
                if (matrix[i][0] == 0) {
                    colHasZero = true;
                    break;
                }
            }
            for (int j = 0; j < n; ++j) {
                if (matrix[0][j] == 0) {
                    rowHasZero = true;
                    break;
                }
            }

            // 将第一行第一列代替o1做法中的两个布尔数组
            for (int i = 1; i < m; ++i) {
                for (int j = 1; j < n; ++j) {
                    if (matrix[i][j] == 0) {
                        matrix[i][0] = 0;
                        matrix[0][j] = 0;
                    }
                }
            }
            for (int i = 1; i < m; ++i) {
                for (int j = 1; j < n; ++j) {
                    if (matrix[i][0] == 0 || matrix[0][j] == 0) {
                        matrix[i][j] = 0;
                    }
                }
            }
            // 最后修改第一行第一列
            if (rowHasZero) {
                for (int j = 0; j < n; ++j) {
                    matrix[0][j] = 0;
                }
            }
            if (colHasZero) {
                for (int i = 0; i < m; ++i) {
                    matrix[i][0] = 0;
                }
            }
        }
    };
}

