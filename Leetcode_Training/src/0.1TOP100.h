namespace s128o1
{
    class Solution {
    public:
        int longestConsecutive(vector<int>& nums) {
            // 去重 + 初始化哈希表
            unordered_set<int> st(nums.begin(), nums.end());

            int ans = 0, n = st.size();
            // 这里容易写成for (int x : nums)，注意
            for (int x : st) {
                // 当前元素不是序列的起点
                if (st.count(x - 1)) {
                    continue;
                }

                // 当前元素是序列的起点
                int y = x + 1;
                while (st.count(y)) {
                    ++y;
                }
                // 序列末尾是y - 1，序列长度是y - 1 - x + 1 = y - x
                ans = max(ans, y - x);

                // 如果出现了长度大于n / 2的序列，就不需要继续遍历
                if (ans * 2 >= n) {
                    return ans;
                }
            }
            return ans;
        }
    };
}

