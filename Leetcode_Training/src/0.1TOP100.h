namespace s2007o1
{   // 本题陷阱在于changed = [4, 8, 2, 16, 1, 8]，如果将4和2配对了，那么会返回{}，实际上为1-2, 4-8配对
    // 还有0的处理也需要留意，因为 0 * 2 = 0
    // 排序 + 哈希表，最简单的做法，但是时间复杂度O(nlogn)，瓶颈在排序
    class Solution {
    public:
        vector<int> findOriginalArray(vector<int>& changed) {
            int m = changed.size();
            if (m % 2 == 1) return {};

            sort(changed.begin(), changed.end());
            unordered_map<int, int> mp;
            for (int x : changed) {
                ++mp[x];
            }
            // 排序后不会出现错位匹配问题，0的问题也可以解决
            vector<int> ans;
            ans.reserve(m / 2);
            for (int x : changed) {
                if (mp[x] == 0) continue;

                if (mp[x * 2] == 0) {
                    return {};
                }

                ans.push_back(x);
                --mp[x];
                --mp[x * 2];
            }
            return ans;
        }
    };
}
namespace s2007o2
{   // 从一组内的最小数字开始的。只要 x / 2 不在数组中，就跳过；找到最小值后通过不断乘二，找到这一组内的其它数字
    // 哈希表 + 分组配对消除，每组间元素为x, 2x, 4x, 8x...关系，时间复杂度O(n)
    class Solution {
    public:
        vector<int> findOriginalArray(vector<int>& changed) {
            if (changed.size() % 2 != 0) {
                return {};
            }

            vector<int> result;
            result.reserve(changed.size() / 2);

            unordered_map<int, int> freq;
            for (int num : changed) {
                ++freq[num];
            }


            // 因为与下面分组处理最小的代码逻辑不符，0无论多少倍都是自身，需要单独处理0
            if (freq.count(0)) {
                if (freq[0] % 2 != 0) {
                    return {};
                }
                result.insert(result.end(), freq[0] / 2, 0);
                freq.erase(0);

            }

            // 注意，这里遍历的是freq而不是原数组
            for (auto& [num, count] : freq) {
                // count等于0的情况只可能是2x, 4x, 8x等元素被配对消去了，故跳过
                // 这个判断不加也正确，因为2x, 4x等元素在下一个判断中也会被跳过
                if (count == 0) continue;

                // 如果 num/2 在 freq 中，则跳过
                if (num % 2 == 0 && freq.count(num / 2)) {
                    continue;
                }

                // 如果 num 为当前分组的最小值
                // 进入内层循环，把 x, 2x, 4x, 8x ... 等全部配对
                int current = num;
                while (freq.count(current)) {
                    // 每次循环，都将current和next全数配对
                    int next = current * 2;
                    // 无法配对，至少要有freq[current]个next(先判断next在不在哈希表里，避免增加哈希表元素，因为外层在用迭代器遍历哈希表)
                    if (!freq.count(next) || freq[current] > freq[next]) {
                        return {};
                    }
                    result.insert(result.end(), freq[current], current);
                    freq[next] -= freq[current];

                    // 检查当前元素和其双倍元素是否一一配对，若一一配对则跳过组内下一元素，改成4x，否则继续配对2x
                    current = (freq[next] == 0) ? next * 2 : next;
                }
            }

            return result;
        }
    };
}
