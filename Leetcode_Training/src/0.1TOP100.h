namespace s49m1 
{   // 对于每个字符串，将其排序，字母异位词的排序结果是一致的，再将排序后的字符串作为哈希表的键值
    class Solution {
    public:
        vector<vector<string>> groupAnagrams(vector<string>& strs) {
            // vector<string>也可以作为哈希表的value，哈希表只对key有要求
            unordered_map<string, vector<string>> mp;
            for (const auto& str : strs) {
                string s = str;
                sort(s.begin(), s.end());
                mp[s].push_back(str);// 注意push_back原本未排序的str
                // 访问mp[s]时，因为访问了一个不存在的键，会自动完成pair的空初始化，创建一个空的vector
                // 所以接下来的push_back也是没有问题的
            }

            vector<vector<string>> ans;
            ans.reserve(mp.size());
            for (auto& p : mp) {
                ans.push_back(move(p.second));
            }
            return ans;
        }
    };
}

